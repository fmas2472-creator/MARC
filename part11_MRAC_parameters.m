%% =====================================================================
%% Part 11: MRAC Parameters
%% منبع واحد تعریف پارامترهای کنترل تطبیقی
%% =====================================================================

fprintf('\n============================================\n');
fprintf('   PART 11 - MRAC PARAMETERS\n');
fprintf('============================================\n');

%% -------------------------------------------------
%% مدل پنج‌حالته انتخاب‌شده از Part 4
%% -------------------------------------------------

sys_MRAC = sys_ss_selected;

A5 = sys_MRAC.A;
B5 = sys_MRAC.B;
C5 = sys_MRAC.C;
D5 = sys_MRAC.D;

fprintf('MRAC model order = %d\n',order(sys_MRAC));

%% -------------------------------------------------
%% مدل‌های مرجع ساخته‌شده در Part 9
%% -------------------------------------------------

Mr_eta_ss = ss(Mr_eta);
Mr_T_ss   = ss(Mr_T);

% مدل مرجع ویسکوزیته
Am_eta = Mr_eta_ss.A;
Bm_eta = Mr_eta_ss.B;
Cm_eta = Mr_eta_ss.C;
Dm_eta = Mr_eta_ss.D;

% مدل مرجع دما
Am_T = Mr_T_ss.A;
Bm_T = Mr_T_ss.B;
Cm_T = Mr_T_ss.C;
Dm_T = Mr_T_ss.D;

%% -------------------------------------------------
%% بهره‌های یادگیری MIT
%% -------------------------------------------------

% توجه: قانون MIT نرمال‌شده است (m2 = 1+phi'*phi) و m2 در این پروژه ~۱۱ است،
% پس بهره‌ی مؤثر = gamma/11. gamma باید با همین مقیاس تنظیم شود.
gamma_eta = 0.30;
gamma_T   = 4.00;
epsilon = 1e-6;
%% -------------------------------------------------
%% حدود ضرایب تطبیقی
%% این حدود برای W بدون بعد هستند.
%% در مرحله فعلی فقط ذخیره می‌شوند و اعمال نمی‌شوند.
%% -------------------------------------------------

theta_min = -60;
theta_max = 60;

%% -------------------------------------------------
%% نقطه کار ورودی‌ها از Part 1
%% -------------------------------------------------

Qi_ss = p.Qi_bar;
Qc_ss = p.Qc_bar;

%% -------------------------------------------------
%% محدودیت تغییرات ورودی‌ها
%% -------------------------------------------------

dQi_min = -200;
dQi_max = 200;

dQc_min = -300;
dQc_max = 300;
% قید فیزیکی: باز/بسته‌کردن کامل شیر خنک‌کننده حداکثر ۲.۷ K روی دمای راکتور
% اثر دارد  ⇒  |Kdc(2,2)|*300 ≈ 2.7 K  (Kdc(2,2) ≈ 0.009 K/(L/h))
%% -------------------------------------------------
%% پارامترهای قبلی Anti-windup و Leakage
%% فعلاً در قانون تطبیق اعمال نمی‌شوند.
%% -------------------------------------------------

K_aw = 1;
sigma = 0.001;

fprintf('MIT config: gamma_eta=%.3g | gamma_T=%.3g | sigma=%.3g | K_aw=%.3g\n',gamma_eta,gamma_T,sigma,K_aw);
%% -------------------------------------------------
%% هدف و مقیاس خروجی‌ها
%% -------------------------------------------------

target = [
    0.1;
    0.1
];

ys = [
    0.1;
    0.1
];

%% -------------------------------------------------
%% مقدار اولیه ضرایب تطبیقی
%% W = [Wr Wy]
%% phi = [r_eta/ys(1); r_T/ys(2); -eta/ys(1); -T/ys(2)]
%% -------------------------------------------------

n_phi = 4;

Kmr = diag([dcgain(Mr_eta_ss), dcgain(Mr_T_ss)]);
Theta0 = [0.2687 0.2687 0.4935 -0.9159; 2.3698 2.3698 0.0594 3.7917];
fprintf('Theta0: max|W| = %.3f\n', max(abs(Theta0(:))));

%% -------------------------------------------------
%% شرایط اولیه سیستم، مدل مرجع و حساسیت‌ها
%% -------------------------------------------------

x0 = zeros(size(A5,1),1);

xm0 = zeros(size(Am_eta,1) + size(Am_T,1),1);

S0 = zeros(size(A5,1),numel(Theta0));

%% -------------------------------------------------
%% زمان شبیه‌سازی
%% -------------------------------------------------

t_final = 150;

n_samples = 3001;

%% -------------------------------------------------
%% تنظیمات حل‌گر
%% -------------------------------------------------

ode_options = odeset( ...
    'RelTol',1e-8, ...
    'AbsTol',1e-10, ...
    'MaxStep',0.05);

%% -------------------------------------------------
%% ذخیره پارامترهای MRAC
%% -------------------------------------------------

%% -------------------------------------------------
%% دبی‌های نامی پلنت (برای قیدهای فیزیکی کران ورودی)
%% -------------------------------------------------
% این‌ها در منبع واحد ذخیره می‌شوند تا build_mrac_config بتواند قیدهای
% Qi >= 0 و Qs = 1.5*Qm - Qi >= 0 را بدون هیچ عدد سخت‌کدشده اعمال کند.

Qi_bar = p.Qi_bar;
Qc_bar = p.Qc_bar;
Qm_bar = p.Qm_bar;
Qs_bar = p.Qs_bar;

save('MRAC_parameters.mat', ...
    'A5','B5','C5','D5', ...
    'Am_eta','Bm_eta','Cm_eta','Dm_eta', ...
    'Am_T','Bm_T','Cm_T','Dm_T', ...
    'gamma_eta','gamma_T', ...
    'epsilon', ...
    'theta_max','theta_min', ...
    'Qi_ss','Qc_ss', ...
    'dQi_max','dQi_min', ...
    'dQc_max','dQc_min', ...
    'K_aw','sigma', ...
    'n_phi','Theta0', ...
    'target','ys', ...
    'x0','xm0','S0', ...
    'Qi_bar','Qc_bar','Qm_bar','Qs_bar', ...
    't_final','n_samples','ode_options');

fprintf('\nMRAC parameters saved.\n');
fprintf('Part 11 completed.\n');
